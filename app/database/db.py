class ConnectionAdapter:
    def __init__(self, connection, is_postgres):
        self.connection = connection
        self.is_postgres = is_postgres

    def execute(self, query, params=()):
        if self.is_postgres:
            query = query.replace("?", "%s")
        return self.connection.execute(query, params)

    def executescript(self, script):
        if self.is_postgres:
            raise RuntimeError("executescript is only supported by SQLite")
        return self.connection.executescript(script)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


class Database:
    def __init__(self, path: str, database_url: str = ""):
        self.path = path
        self.database_url = database_url
        self.is_postgres = bool(database_url)

        if not self.is_postgres:
            Path(path).parent.mkdir(parents=True, exist_ok=True)

    def _raw_connect(self):
        if self.is_postgres:
            return psycopg.connect(
                self.database_url,
                row_factory=dict_row,
                connect_timeout=15,
            )

        conn = sqlite3.connect(self.path, timeout=20)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")
        return conn

    @contextmanager
    def connect(self):
        conn = ConnectionAdapter(self._raw_connect(), self.is_postgres)
        try:
            yield conn
        finally:
            conn.close()

    @contextmanager
    def transaction(self):
        conn = ConnectionAdapter(self._raw_connect(), self.is_postgres)
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()

    def initialize(self):
        if self.is_postgres:
            with self.transaction() as conn:
                for statement in POSTGRES_SCHEMA.split(";"):
                    if statement.strip():
                        conn.execute(statement)
        else:
            with self.transaction() as conn:
                conn.executescript(SQLITE_SCHEMA)


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")
